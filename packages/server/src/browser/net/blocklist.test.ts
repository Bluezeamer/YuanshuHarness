import { describe, expect, test } from "vitest";
import { isBlockedAddress } from "./blocklist.js";

// 每个网段的边界两侧都要测：拦错一边就是 SSRF 或误伤。
const cases: [string, boolean][] = [
  // 0.0.0.0/8
  ["0.0.0.0", true],
  ["0.255.255.255", true],
  ["1.0.0.1", false],
  // 10.0.0.0/8
  ["10.0.0.0", true],
  ["10.255.255.255", true],
  ["9.255.255.255", false],
  ["11.0.0.0", false],
  // 100.64.0.0/10（含 Tailscale）
  ["100.64.0.1", true],
  ["100.100.100.100", true],
  ["100.127.255.255", true],
  ["100.63.255.255", false],
  ["100.128.0.1", false],
  // 127.0.0.0/8
  ["127.0.0.1", true],
  ["127.255.255.254", true],
  ["128.0.0.1", false],
  // 169.254.0.0/16（云元数据）
  ["169.254.169.254", true],
  ["169.253.255.255", false],
  ["169.255.0.0", false],
  // 172.16.0.0/12
  ["172.16.0.1", true],
  ["172.31.255.255", true],
  ["172.15.255.255", false],
  ["172.32.0.0", false],
  // 192.0.0.0/24
  ["192.0.0.1", true],
  ["192.0.1.1", false],
  // 192.168.0.0/16
  ["192.168.1.1", true],
  ["192.167.255.255", false],
  ["192.169.0.0", false],
  // 198.18.0.0/15
  ["198.18.0.1", true],
  ["198.19.255.255", true],
  ["198.17.255.255", false],
  ["198.20.0.0", false],
  // 224.0.0.0/4 与 240.0.0.0/4
  ["224.0.0.1", true],
  ["239.255.255.255", true],
  ["240.0.0.1", true],
  ["255.255.255.255", true],
  ["223.255.255.255", false],
  // 公网
  ["8.8.8.8", false],
  ["1.1.1.1", false],
  // IPv6
  ["::", true],
  ["::1", true],
  ["::2", false],
  ["fc00::1", true],
  ["fd7a:115c:a1e0::1", true],
  ["fbff::1", false],
  ["fe80::1", true],
  ["fe80::1%eth0", true],
  ["fec0::1", false],
  ["ff02::1", true],
  ["64:ff9b::1", true],
  ["64:ff9b:1::1", false],
  ["2001:4860:4860::8888", false],
  // IPv4 映射的 IPv6 按 IPv4 判
  ["::ffff:127.0.0.1", true],
  ["::ffff:10.0.0.1", true],
  ["::ffff:169.254.169.254", true],
  ["::ffff:8.8.8.8", false],
  // 不是 IP 一律当禁止
  ["", true],
  ["localhost", true],
  ["999.1.1.1", true],
  ["::ffff:127.0.0.1.5", true],
];

describe("isBlockedAddress", () => {
  test.each(cases)("%s → %s", (ip, blocked) => {
    expect(isBlockedAddress(ip)).toBe(blocked);
  });
});
